#!/usr/bin/env python3
"""Apply Kyro's app identity to Silo's generated string catalogs (iOS branch).

Upstream Silo moved user-facing text into string catalogs generated by
silo-translations. Their English text names the app "Silo". Kyro keeps the
rule recorded in `Components/AppBrand.swift`: the app is Kyro, while the
backend keeps Silo terminology ("Silo server", "Silo password", "Silo
Diagnostics"), and so does the Silo app that runs on a Roku.

Run after every translation sync (`scripts/sync-translations`):

    python3 scripts/kyro_brand_catalog.py            # rewrite in place
    python3 scripts/kyro_brand_catalog.py --check    # exit 1 if a rewrite is due

English values are rewritten word by word. A translation is rewritten only
when its English value had every "Silo" rebranded, so word order in other
languages can never pair Kyro with a server term.

This changes the catalogs' contents, so `.silo-translations`' sha256 no
longer matches them; that is expected on Kyro branches.
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGS = [
    ROOT / "iosApp/iosApp/Localizable.xcstrings",
    ROOT / "iosApp/InfoPlist/iOS/InfoPlist.xcstrings",
]
APP = "Kyro"

# "Silo" stays when it names the server, its accounts or its hosted service.
KEEP_AFTER = re.compile(
    r"(?:['’]s)?\s+(?:server|Server|servers|Servers|password|Password|account|Account|"
    r"Diagnostics|website|port|mobile app)\b"
)
WORD = re.compile(r"\bSilo\b")

# Text about the server's address or the Silo app on a Roku keeps Silo.
KEEP_KEYS = {
    "setup.body",
    "setup.advanced.hint",
    "setup.recovery.leadNotRecognized",
    "profiles.error.passwordReset",
    "cast.remote.error.lostRoku",
    "remote.error.requiresPairing",
    "remote.error.unreachableRoku",
    "remote.picker.rokuMissing",
    "remote.reconnect.rokuHint",
}
# Mixed sentences, written out (English only).
OVERRIDES = {
    "remote.picker.noneFoundHint":
        "TVs on this server appear here while Kyro is open on them. On a Roku, open Silo with the Roku remote.",
}


def rebrand_en(value: str) -> str:
    def sub(match: re.Match) -> str:
        if KEEP_AFTER.match(value, match.end()):
            return match.group(0)
        return APP
    return WORD.sub(sub, value)


def string_units(node):
    """Yields every stringUnit dict under a localization (plurals, devices)."""
    if isinstance(node, dict):
        unit = node.get("stringUnit")
        if isinstance(unit, dict) and isinstance(unit.get("value"), str):
            yield unit
        for key, child in node.items():
            if key != "stringUnit":
                yield from string_units(child)
    elif isinstance(node, list):
        for child in node:
            yield from string_units(child)


def dump(data) -> str:
    """Xcode's catalog formatting: escaped invisible format characters."""
    text = json.dumps(data, ensure_ascii=False, indent=2, separators=(",", " : "))
    text = "".join(
        f"\\u{ord(c):04X}" if unicodedata.category(c) in ("Cf", "Zl", "Zp") else c
        for c in text
    )
    return text + "\n"


def process(path: Path) -> int:
    data = json.loads(path.read_text(encoding="utf-8"))
    changed = 0
    for key, entry in data.get("strings", {}).items():
        locs = entry.get("localizations", {})
        en = locs.get("en")
        if not en or key in KEEP_KEYS:
            continue
        en_units = list(string_units(en))
        if not any("Silo" in u["value"] for u in en_units):
            continue
        fully = True
        for unit in en_units:
            new = OVERRIDES.get(key) or rebrand_en(unit["value"])
            if WORD.search(new):
                fully = False
            if new != unit["value"]:
                unit["value"] = new
                changed += 1
        if not fully:
            continue
        for lang, loc in locs.items():
            if lang == "en":
                continue
            for unit in string_units(loc):
                new = unit["value"].replace("Silo", APP)
                if new != unit["value"]:
                    unit["value"] = new
                    changed += 1
    if changed and "--check" not in sys.argv:
        path.write_text(dump(data), encoding="utf-8")
    return changed


def main() -> int:
    total = 0
    for path in CATALOGS:
        n = process(path)
        print(f"{path.relative_to(ROOT)}: {n} value(s) {'need' if '--check' in sys.argv else 'rewritten'}")
        total += n
    return 1 if ("--check" in sys.argv and total) else 0


if __name__ == "__main__":
    sys.exit(main())
